export const SERVICE_SEO_BY_ID = new Map<string, ServiceSeoItem>(
  SERVICE_SEO_LIST.map((item) => [item.id, item])
);

export const SERVICE_SEO_BY_SLUG = new Map<string, ServiceSeoItem>(
  SERVICE_SEO_LIST.map((item) => [item.slug, item])
);

export const getServiceSeoByIdOrSlug = (identifier?: string): ServiceSeoItem | undefined => {
  if (!identifier) return undefined;
  return SERVICE_SEO_BY_ID.get(identifier) || SERVICE_SEO_BY_SLUG.get(identifier);
};

export const resolveServiceId = (identifier?: string): string => {
  if (!identifier) return "";
  const item = SERVICE_SEO_BY_SLUG.get(identifier);
  return item ? item.id : identifier;
};
